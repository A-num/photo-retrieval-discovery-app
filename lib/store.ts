import { promises as fs } from "node:fs";
import path from "node:path";
import type { Conversation, ConversationAnalysis, Dataset, ProblemCluster } from "@/types";
import { PROBLEM_HYPOTHESES } from "@/data/problem-clusters";

// Local JSON persistence for collected conversations, their analyses and regenerated insights.
// Swap this module for a Supabase/Postgres implementation without touching callers.

export interface ImportBatch {
  id: string;
  filename: string;
  createdAt: string;
  count: number;
  relevant: number;
  analyzedBy: string;
}

interface StoreFile {
  imports: ImportBatch[];
  conversations: Conversation[];
  analyses: Record<string, ConversationAnalysis>;
  /** Problems regenerated by Claude; when absent, the starting hypotheses are used. */
  problems?: ProblemCluster[];
}

const EMPTY: StoreFile = { imports: [], conversations: [], analyses: {} };

function storePath() {
  return process.env.DISCOVERY_STORE_PATH ?? path.join(process.cwd(), ".data", "store.json");
}

async function readStore(): Promise<StoreFile> {
  try {
    const raw = await fs.readFile(/*turbopackIgnore: true*/ storePath(), "utf8");
    return { ...EMPTY, ...(JSON.parse(raw) as StoreFile) };
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") return structuredClone(EMPTY);
    throw err;
  }
}

async function writeStore(store: StoreFile) {
  const file = storePath();
  await fs.mkdir(/*turbopackIgnore: true*/ path.dirname(file), { recursive: true });
  const tmp = `${file}.tmp`;
  await fs.writeFile(/*turbopackIgnore: true*/ tmp, JSON.stringify(store, null, 2));
  await fs.rename(/*turbopackIgnore: true*/ tmp, file);
}

export async function getDataset(): Promise<Dataset> {
  const store = await readStore();
  const problems = store.problems ?? PROBLEM_HYPOTHESES;
  const opportunityByProblem = new Map(problems.map((p) => [p.id, p.opportunity.title]));
  const analyses: Record<string, ConversationAnalysis> = {};
  for (const [id, a] of Object.entries(store.analyses)) {
    analyses[id] = {
      ...a,
      opportunityArea:
        a.opportunityArea ?? (a.problemId ? opportunityByProblem.get(a.problemId) : undefined),
    };
  }
  return {
    conversations: store.conversations,
    analyses,
    problems,
  };
}

export async function getImports(): Promise<ImportBatch[]> {
  return (await readStore()).imports;
}

export async function addImport(
  batch: ImportBatch,
  conversations: Conversation[],
  analyses: ConversationAnalysis[],
) {
  const store = await readStore();
  store.imports.push(batch);
  store.conversations.push(...conversations);
  for (const a of analyses) store.analyses[a.conversationId] = a;
  await writeStore(store);
}

export async function deleteImport(batchId: string) {
  const store = await readStore();
  const removed = new Set(
    store.conversations.filter((c) => c.dataset === batchId).map((c) => c.id),
  );
  store.imports = store.imports.filter((b) => b.id !== batchId);
  store.conversations = store.conversations.filter((c) => !removed.has(c.id));
  for (const id of removed) delete store.analyses[id];
  await writeStore(store);
}

export async function saveProblems(problems: ProblemCluster[] | undefined) {
  const store = await readStore();
  store.problems = problems;
  await writeStore(store);
}

/** Replaces the analyses for existing conversations (e.g. after re-analysis) and refreshes batch counts. */
export async function updateAnalyses(analyses: ConversationAnalysis[]) {
  const store = await readStore();
  const known = new Set(store.conversations.map((c) => c.id));
  const unknown = analyses.filter((a) => !known.has(a.conversationId)).map((a) => a.conversationId);
  if (unknown.length) throw new Error(`Unknown conversation ids: ${unknown.slice(0, 5).join(", ")}`);
  for (const a of analyses) store.analyses[a.conversationId] = a;
  const batchOf = new Map(store.conversations.map((c) => [c.id, c.dataset]));
  for (const b of store.imports) {
    const ids = store.conversations.filter((c) => batchOf.get(c.id) === b.id).map((c) => c.id);
    b.relevant = ids.filter((id) => store.analyses[id]?.retrievalRelevant).length;
    const modes = new Set(ids.map((id) => store.analyses[id]?.analyzedBy));
    b.analyzedBy = modes.size === 1 ? [...modes][0]! : "mixed";
  }
  await writeStore(store);
}
