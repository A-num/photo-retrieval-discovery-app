export function Chips({
  items,
  variant = "neutral",
  counts,
}: {
  items: { label: string; count?: number }[] | string[];
  variant?: "neutral" | "remember" | "forget" | "failure";
  counts?: boolean;
}) {
  const styles = {
    neutral: "bg-muted text-foreground",
    remember: "bg-emerald-50 text-emerald-800 ring-1 ring-emerald-200 dark:bg-emerald-950 dark:text-emerald-200 dark:ring-emerald-800",
    forget: "bg-rose-50 text-rose-800 ring-1 ring-rose-200 dark:bg-rose-950 dark:text-rose-200 dark:ring-rose-800",
    failure: "bg-amber-50 text-amber-900 ring-1 ring-amber-200 dark:bg-amber-950 dark:text-amber-200 dark:ring-amber-800",
  }[variant];
  const list = items.map((i) => (typeof i === "string" ? { label: i } : i));
  if (!list.length) return <span className="text-sm text-muted-foreground">None recorded</span>;
  return (
    <div className="flex flex-wrap gap-1.5">
      {list.map((i) => (
        <span key={i.label} className={cn("inline-flex items-center gap-1 rounded-md px-2 py-0.5 text-xs", styles)}>
          {i.label}
          {counts && i.count !== undefined && <span className="tabular-nums opacity-60">{i.count}</span>}
        </span>
      ))}
    </div>
  );
}

