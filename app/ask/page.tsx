import { hasClaude } from "@/lib/ai/client";
import { AskPanel } from "@/components/ask-panel";
import { DatasetBanner } from "@/components/labels";
import { getDataset } from "@/lib/store";

export const dynamic = "force-dynamic";

export default async function AskPage() {
  const claude = hasClaude();
  const ds = await getDataset();
  return (
    <>
      <DatasetBanner ds={ds} />
      <header className="mb-5">
        <h1 className="text-2xl font-semibold tracking-tight">Ask AI</h1>
        <p className="mt-1 max-w-3xl text-sm text-muted-foreground">
          A research assistant that answers only from the analyzed conversations, and shows the evidence behind every answer.{" "}
          {claude
            ? "Answers are generated by Claude."
            : "No API key is configured, so answers are computed locally from the analysis. Set ANTHROPIC_API_KEY for open-ended questions."}
        </p>
      </header>
      <AskPanel />
    </>
  );
}
